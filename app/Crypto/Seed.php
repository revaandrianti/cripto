    /** @var list<int> 32 kata subkunci (Ki0, Ki1) x 16 ronde */
    private array $ki;

    public function __construct(string $kunci16)
    {
        if (strlen($kunci16) !== 16) {
            throw new \InvalidArgumentException('Kunci SEED harus tepat 16 byte.');
        }

        self::siapkanSsBox();
        $this->ki = $this->jadwalKunci($kunci16);
    }

    /** Enkripsi satu blok 128 bit. */
    public function enkripsiBlok(string $blok): string
    {
        [$l, $r] = $this->belah($blok);

        for ($i = 0; $i < 15; $i++) {
            $t = $r;
            [$f0, $f1] = $this->f($this->ki[2 * $i], $this->ki[2 * $i + 1], $r);
            $r = [$l[0] ^ $f0, $l[1] ^ $f1];
            $l = $t;
        }

        // Ronde ke-16: L ^= F(K16, R), R tetap.
        [$f0, $f1] = $this->f($this->ki[30], $this->ki[31], $r);
        $l = [$l[0] ^ $f0, $l[1] ^ $f1];

        return pack('N4', $l[0], $l[1], $r[0], $r[1]);
    }

    /** Dekripsi satu blok: struktur sama, subkunci terbalik. */
    public function dekripsiBlok(string $blok): string
    {
        [$l, $r] = $this->belah($blok);

        for ($i = 0; $i < 15; $i++) {
            $t = $r;
            [$f0, $f1] = $this->f($this->ki[30 - 2 * $i], $this->ki[31 - 2 * $i], $r);
            $r = [$l[0] ^ $f0, $l[1] ^ $f1];
            $l = $t;
        }

        [$f0, $f1] = $this->f($this->ki[0], $this->ki[1], $r);
        $l = [$l[0] ^ $f0, $l[1] ^ $f1];

        return pack('N4', $l[0], $l[1], $r[0], $r[1]);
    }

    /**
     * @return array{array{int, int}, array{int, int}} pasangan (L, R)
     */
    private function belah(string $blok): array
    {
        $kata = unpack('N4', $blok);

        return [
            [$kata[1], $kata[2]],
            [$kata[3], $kata[4]],
        ];
    }

    /**
     * Fungsi ronde F(Ki0, Ki1, R): R0 kata atas, R1 kata bawah.
     *
     * @param  array{int, int}  $r
     * @return array{int, int} (R0', R1')
     */
    private function f(int $ki0, int $ki1, array $r): array
    {
        $r0K = $r[0] ^ $ki0;
        $x = $r0K ^ ($r[1] ^ $ki1);
        $dalam = self::g($x);
        $tengah = self::g(self::tambah($r0K, $dalam));
        $r1p = self::g(self::tambah($tengah, $dalam));

        return [self::tambah($r1p, $tengah), $r1p];
    }

    /** G: empat SS-box berdasarkan byte X0..X3 (X0 byte terendah). */
    private static function g(int $x): int
    {
        return self::$ss0[$x & 0xFF]
            ^ self::$ss1[($x >> 8) & 0xFF]
            ^ self::$ss2[($x >> 16) & 0xFF]
            ^ self::$ss3[($x >> 24) & 0xFF];
    }

    private static function tambah(int $a, int $b): int
    {
        return ($a + $b) & 0xFFFFFFFF;
    }

    /** Jadwal kunci: 16 pasangan subkunci (RFC 4269 §2.3). */
    private function jadwalKunci(string $kunci): array
    {
        $kata = unpack('N4', $kunci);
        $key0 = $kata[1];
        $key1 = $kata[2];
        $key2 = $kata[3];
        $key3 = $kata[4];
        $ki = [];

        for ($i = 0; $i < 16; $i++) {
            $ki[] = self::g(($key0 + $key2 - self::KC[$i]) & 0xFFFFFFFF);
            $ki[] = self::g(($key1 - $key3 + self::KC[$i]) & 0xFFFFFFFF);

            if ($i % 2 === 0) {
                // Ronde ganjil (1, 3, ...): Key0||Key1 dirotasi kanan 8 bit.
                $bawaan = $key1 & 0xFF;
                $key1 = (($key1 >> 8) | (($key0 & 0xFF) << 24)) & 0xFFFFFFFF;
                $key0 = (($key0 >> 8) | ($bawaan << 24)) & 0xFFFFFFFF;
            } else {
                // Ronde genap: Key2||Key3 dirotasi kiri 8 bit.
                $kepala = ($key3 >> 24) & 0xFF;
                $key3 = (($key3 << 8) | (($key2 >> 24) & 0xFF)) & 0xFFFFFFFF;
                $key2 = (($key2 << 8) | $kepala) & 0xFFFFFFFF;
            }
        }

        return $ki;
    }

    /** Hitung SS0..SS3 dari S0/S1 sesuai definisi RFC 4269 §2.2. */
    private static function siapkanSsBox(): void
    {
        if (isset(self::$ss0)) {
            return;
        }

        for ($i = 0; $i < 256; $i++) {
            $v0 = self::S0[$i];
            $v1 = self::S1[$i];

            self::$ss0[$i] = (($v0 & 0x3F) << 24) | (($v0 & 0xCF) << 16) | (($v0 & 0xF3) << 8) | ($v0 & 0xFC);
            self::$ss1[$i] = (($v1 & 0xFC) << 24) | (($v1 & 0x3F) << 16) | (($v1 & 0xCF) << 8) | ($v1 & 0xF3);
            self::$ss2[$i] = (($v0 & 0xF3) << 24) | (($v0 & 0xFC) << 16) | (($v0 & 0x3F) << 8) | ($v0 & 0xCF);
            self::$ss3[$i] = (($v1 & 0xCF) << 24) | (($v1 & 0xF3) << 16) | (($v1 & 0xFC) << 8) | ($v1 & 0x3F);
        }
    }
